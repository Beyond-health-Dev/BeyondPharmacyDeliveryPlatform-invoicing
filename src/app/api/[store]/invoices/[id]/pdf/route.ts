import { NextRequest, NextResponse } from "next/server";
import { prisma } from "@/lib/db";
import { auth } from "@/lib/auth";
import { resolveStore } from "@/lib/store";
import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";
import { rgbTuple } from "@/styles/tokens";

// Period and delivery dates are stored as UTC midnights, so read them in UTC;
// createdAt is a moment in time, shown on Vancouver's calendar.
const storedDate = (value: Date) => new Date(value).toLocaleDateString("en-US", { timeZone: "UTC" });
const vancouverDate = (value: Date) =>
  new Date(value).toLocaleDateString("en-US", { timeZone: "America/Vancouver" });

export async function GET(
  _req: NextRequest,
  { params }: { params: Promise<{ store: string; id: string }> }
) {
  const { store: storeSlug, id } = await params;
  const store = await resolveStore(storeSlug);
  if (!store) {
    return NextResponse.json({ error: "Store not found" }, { status: 404 });
  }

  const session = await auth();
  if (!session?.user || session.user.role !== "PHARMACY_ADMIN") {
    return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  }

  const invoice = await prisma.invoice.findUnique({
    where: { id, storeId: store.id },
    include: {
      lineItems: { include: { order: true } },
      generatedBy: true,
      driver: true,
    },
  });

  if (!invoice) {
    return NextResponse.json({ error: "Invoice not found" }, { status: 404 });
  }

  // Generate PDF (colours from the design tokens: navy text, navy table
  // header with cream text, cream stripes, mint total row).
  const doc = new jsPDF();
  doc.setTextColor(...rgbTuple("navy"));

  // Header — include store name
  doc.setFontSize(20);
  doc.text(store.name, 14, 22);
  doc.setFontSize(10);
  doc.text("Delivery Invoice", 14, 30);

  doc.setFontSize(12);
  doc.text(`Invoice: ${invoice.invoiceNumber}`, 14, 45);
  doc.setFontSize(10);
  doc.text(
    `Period: ${storedDate(invoice.periodStart)} – ${storedDate(invoice.periodEnd)}`,
    14,
    52
  );
  doc.text(`Generated: ${vancouverDate(invoice.createdAt)}`, 14, 58);
  doc.text(`Generated by: ${invoice.generatedBy.name}`, 14, 64);
  doc.text(`Driver: ${invoice.driver?.name ?? "Unassigned"}`, 14, 70);

  // Table
  const tableData = invoice.lineItems.map((item, i) => [
    i + 1,
    storedDate(item.order.scheduledDate),
    item.order.patientName,
    item.description,
    `$${item.amount.toFixed(2)}`,
  ]);

  autoTable(doc, {
    startY: 78,
    head: [["#", "Date", "Patient", "Description", "Amount"]],
    body: tableData,
    foot: [["", "", "", "Total", `$${invoice.totalAmount.toFixed(2)}`]],
    theme: "striped",
    styles: { textColor: rgbTuple("navy") },
    headStyles: { fillColor: rgbTuple("navy"), textColor: rgbTuple("cream") },
    alternateRowStyles: { fillColor: rgbTuple("panelCream") },
    footStyles: { fillColor: rgbTuple("mint"), textColor: rgbTuple("navy"), fontStyle: "bold" },
  });

  const pdfBuffer = Buffer.from(doc.output("arraybuffer"));

  return new NextResponse(pdfBuffer, {
    headers: {
      "Content-Type": "application/pdf",
      "Content-Disposition": `attachment; filename="${invoice.invoiceNumber}.pdf"`,
    },
  });
}
